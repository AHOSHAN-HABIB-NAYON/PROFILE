async function seedBase() {
  const catCount = Number(await db.val('SELECT COUNT(*) FROM categories'));
  if (!catCount) {
    let sort = 1;
    for (const [name, icon, color, description] of CATEGORIES) {
      await db.insert('categories', { name, slug: slugify(name), icon, color, description, sort: sort++ });
    }
  }
  const pageCount = Number(await db.val('SELECT COUNT(*) FROM pages'));
  if (!pageCount) {
    let sort = 1;
    for (const [title, slug, content] of PAGES) await db.insert('pages', { title, slug, content, sort: sort++ });
  }
}

