            'port' => (int) ($_POST['db_port'] ?? 3306) ?: 3306,
            'name' => trim((string) ($_POST['db_name'] ?? '')),
            'user' => trim((string) ($_POST['db_user'] ?? '')),
            'pass' => (string) ($_POST['db_pass'] ?? ''),
            'charset' => 'utf8mb4',
        ];
        $adminName = trim((string) ($_POST['admin_name'] ?? ''));
        $adminEmail = strtolower(trim((string) ($_POST['admin_email'] ?? '')));
        $adminPass = (string) ($_POST['admin_pass'] ?? '');
        if ($db['name'] === '' || $db['user'] === '') {
            $error = 'ডাটাবেসের নাম ও ইউজার দিন।';
        } elseif ($adminName === '' || !filter_var($adminEmail, FILTER_VALIDATE_EMAIL) || strlen($adminPass) < 10) {
            $error = 'অ্যাডমিনের নাম, সঠিক ইমেইল এবং কমপক্ষে ১০ অক্ষরের পাসওয়ার্ড দিন।';
        } else {
            try {
                $pdo = new PDO(sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $db['host'], $db['port'], $db['name']), $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
                $pdo->exec('SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci');
                $pdo->exec("ALTER DATABASE `" . str_replace('`', '', $db['name']) . "` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
                foreach (install_split_sql((string) file_get_contents(ROOT . '/database/database.sql')) as $stmt) {
                    $pdo->exec($stmt);
                }
                $appKey = base64_encode(random_bytes(32));
                $GLOBALS['CONFIG']['db'] = $db;
                $GLOBALS['CONFIG']['app_key'] = $appKey;
                $GLOBALS['CONFIG']['installed'] = true;
                if (!$pdo->query('SELECT COUNT(*) FROM admin_users')->fetchColumn()) {
                    $st = $pdo->prepare("INSERT INTO admin_users (name, email, password_hash, role) VALUES (?, ?, ?, 'super')");
                    $st->execute([$adminName, $adminEmail, password_hash($adminPass, PASSWORD_DEFAULT)]);
                }
                if (WebPush::publicKey() === '') {
                    WebPush::generateKeys();
                }
                Settings::set('contact_email', $adminEmail);
                Settings::set('push_subject', 'mailto:' . $adminEmail);
                $config = "<?php\n// Generated by the installer on " . date('Y-m-d H:i') . ". Keep this file private.\nreturn " . var_export([
                    'installed' => true,
                    'env' => 'production',
                    'db' => $db,
                    'app_key' => $appKey,
                    'base_url' => rtrim(trim((string) ($_POST['base_url'] ?? '')), '/'),
                    'force_https' => !empty($_POST['force_https']),
                ], true) . ";\n";
                if (file_put_contents(ROOT . '/config/config.local.php', $config, LOCK_EX) === false) {
                    throw new RuntimeException('config.local.php লেখা যায়নি');
                }
                @chmod(ROOT . '/config/config.local.php', 0640);
                $done = true;
            } catch (Throwable $e) {
                Logger::error($e);
                $error = 'ইনস্টল সম্পন্ন হয়নি: ' . ($e instanceof PDOException ? 'ডাটাবেস সংযোগ/ইমপোর্ট ব্যর্থ — তথ্য যাচাই করুন।' : $e->getMessage());
            }
        }
    }
}
