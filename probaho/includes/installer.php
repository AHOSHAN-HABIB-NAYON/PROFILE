function install_split_sql(string $sql): array
{
    $out = [];
    $buf = '';
    $len = strlen($sql);
    $quote = null;
    for ($i = 0; $i < $len; $i++) {
        $c = $sql[$i];
        if ($quote === null) {
            if ($c === '-' && ($sql[$i + 1] ?? '') === '-') {
                $nl = strpos($sql, "\n", $i);
                $i = $nl === false ? $len : $nl;
                continue;
            }
            if ($c === "'" || $c === '"' || $c === '`') {
                $quote = $c;
            } elseif ($c === ';') {
                if (trim($buf) !== '') {
                    $out[] = trim($buf);
                }
                $buf = '';
                continue;
            }
        } elseif ($c === '\\') {
            $buf .= $c . ($sql[$i + 1] ?? '');
            $i++;
            continue;
        } elseif ($c === $quote) {
            if (($sql[$i + 1] ?? '') === $quote) {
                $buf .= $c . $c;
                $i++;
                continue;
            }
            $quote = null;
        }
        $buf .= $c;
    }
    if (trim($buf) !== '') {
        $out[] = trim($buf);
    }
    return $out;
}

