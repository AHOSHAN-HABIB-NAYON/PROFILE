// docs/CONTRACTS/navigation.json -> NAVIGATION_MAP.md + app/lib/nav/routes.g.dart, with validation.
import { emit, done, readJson } from './lib.mjs';

const nav = readJson('docs/CONTRACTS/navigation.json');
const ids = new Set(nav.screens.map((s) => s.id));
const overlayIds = new Set(nav.overlays.map((o) => o.id));
const errors = [];

// The language selector appears ONLY in these places (spec LOCALIZATION, STRICT).
const LANGUAGE_SCREENS = new Set(['welcome', 'login_parent', 'login_probashi', 'login_member', 'child_code', 'register',
  'verify_email', 'forgot_email', 'forgot_code', 'forgot_new', 'forgot_done', 'home', 'child_home']);

const seenPaths = new Set();
for (const s of nav.screens) {
  if (seenPaths.has(s.path)) errors.push(`duplicate path ${s.path}`);
  seenPaths.add(s.path);
  if (s.languageSelector !== LANGUAGE_SCREENS.has(s.id)) errors.push(`${s.id}: languageSelector must be ${LANGUAGE_SCREENS.has(s.id)}`);
  const hasLangButton = s.buttons.some((b) => b.to === 'sheet:language');
  if (hasLangButton !== s.languageSelector) errors.push(`${s.id}: language button and languageSelector disagree`);
  for (const b of s.buttons) {
    const [kind, rest] = b.to.includes(':') ? b.to.split(/:(.*)/s) : ['screen', b.to];
    if (kind === 'screen' && !['back', 'close'].includes(b.to) && !ids.has(b.to)) errors.push(`${s.id}: "${b.label}" -> unknown screen ${b.to}`);
    if ((kind === 'sheet' || kind === 'dialog') && !overlayIds.has(rest)) errors.push(`${s.id}: "${b.label}" -> unknown ${kind} ${rest}`);
    if (!['screen', 'sheet', 'dialog', 'system', 'action'].includes(kind)) errors.push(`${s.id}: bad target ${b.to}`);
  }
}
for (const o of nav.overlays) for (const b of o.buttons) {
  if (!b.to.includes(':') && !['close', 'back'].includes(b.to) && !ids.has(b.to)) errors.push(`overlay ${o.id}: unknown target ${b.to}`);
}
for (const t of nav.adultTabs) if (nav.screens.find((s) => s.id === t)?.shell !== 'adult') errors.push(`tab ${t} must have shell=adult`);
if (JSON.stringify(nav.adultTabs) !== JSON.stringify(['home', 'map', 'history', 'premium', 'settings'])) errors.push('adult tabs must be Home, Map, History, Premium, Settings');
if (nav.screens.some((s) => s.roles.includes('child') && s.shell)) errors.push('child screens must not use the bottom bar');
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const target = (to) => {
  if (ids.has(to)) return `[${to}](#${to})`;
  if (to.startsWith('sheet:') || to.startsWith('dialog:')) return `[${to}](#${to.split(':')[1]})`;
  return `\`${to}\``;
};
const md = [
  '<!-- GENERATED by tools/gen-nav.mjs from docs/CONTRACTS/navigation.json. Edit the JSON, not this file. -->',
  '# NAVIGATION_MAP', '',
  'Every visible button with its action and destination. Targets: a screen, `sheet:`/`dialog:` overlays, `back`, `close`, `system:` (an Android system screen or intent) or `action:` (stays on the screen).', '',
  '- **Adult bottom bar:** Home, Map, History, Premium, Settings. **Child:** no bottom bar.',
  `- **Language selector only on:** ${[...LANGUAGE_SCREENS].join(', ')}.`, '',
  '| Screen | Path | Phase | Roles | Language selector |', '|---|---|---|---|---|',
  ...nav.screens.map((s) => `| [${s.title}](#${s.id}) | \`${s.path}\` | ${s.phase} | ${s.roles.join(', ')} | ${s.languageSelector ? 'yes' : 'no'} |`),
  '',
  ...nav.screens.flatMap((s) => [
    `## ${s.id}`, '', `**${s.title}** · \`${s.path}\` · phase ${s.phase}${s.shell ? ' · adult bottom bar' : ''}`, '',
    ...(s.notes ? [s.notes, ''] : []),
    ...(s.buttons.length ? ['| Button | Goes to | Note |', '|---|---|---|', ...s.buttons.map((b) => `| ${b.label} | ${target(b.to)} | ${b.note ?? ''} |`)] : ['_No buttons (automatic transition)._']),
    '',
  ]),
  '# Overlays (sheets and dialogs)', '',
  ...nav.overlays.flatMap((o) => [`## ${o.id}`, '', `**${o.title}** (${o.kind})`, '', '| Button | Goes to | Note |', '|---|---|---|',
    ...o.buttons.map((b) => `| ${b.label} | ${target(b.to)} | ${b.note ?? ''} |`), '']),
].join('\n');
emit('docs/CONTRACTS/NAVIGATION_MAP.md', md + '\n');

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const dart = [
  '// GENERATED by tools/gen-nav.mjs from docs/CONTRACTS/navigation.json. Do not edit.',
  "import 'nav_types.dart';", '',
  'const adultTabs = <String>[' + nav.adultTabs.map(q).join(', ') + '];', '',
  'const screens = <ScreenSpec>[',
  ...nav.screens.map((s) => `  ScreenSpec(id: ${q(s.id)}, path: ${q(s.path)}, title: ${q(s.title)}, phase: ${s.phase}, roles: [${s.roles.map(q).join(', ')}], languageSelector: ${s.languageSelector}, adultShell: ${s.shell === 'adult'}, buttons: [${s.buttons.map((b) => `ButtonSpec(${q(b.label)}, ${q(b.to)})`).join(', ')}]),`),
  '];', '',
  'const overlays = <OverlaySpec>[',
  ...nav.overlays.map((o) => `  OverlaySpec(id: ${q(o.id)}, kind: ${q(o.kind)}, title: ${q(o.title)}, buttons: [${o.buttons.map((b) => `ButtonSpec(${q(b.label)}, ${q(b.to)})`).join(', ')}]),`),
  '];', '',
].join('\n');
emit('app/lib/nav/routes.g.dart', dart);
done(`navigation (${nav.screens.length} screens, ${nav.overlays.length} overlays)`);
