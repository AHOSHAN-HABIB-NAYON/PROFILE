// docs/CONTRACTS/design-tokens.json -> Dart (app) + CSS custom properties (admin/landing).
import { emit, done, readJson } from './lib.mjs';

const t = readJson('docs/CONTRACTS/design-tokens.json');
const hex = (h) => `Color(0xFF${h.slice(1).toUpperCase()})`;
const lines = [];
const block = (cls, obj, fmt) => {
  lines.push(`abstract final class ${cls} {`);
  for (const [k, v] of Object.entries(obj)) if (!k.startsWith('_')) lines.push(`  static ${fmt(k, v)}`);
  lines.push('}', '');
};

lines.push('// GENERATED by tools/gen-tokens.mjs from docs/CONTRACTS/design-tokens.json. Do not edit.',
  "import 'dart:ui';", '');
block('LightColors', { ...t.color.light, ...t.color.accessible_text.light }, (k, v) => `const ${k} = ${hex(v)};`);
block('DarkColors', { ...t.color.dark, ...t.color.accessible_text.dark }, (k, v) => `const ${k} = ${hex(v)};`);
block('BrandColors', t.color.shared, (k, v) => `const ${k} = ${hex(v)};`);
block('Space', t.space, (k, v) => `const double ${k} = ${v};`);
block('Radii', t.radius, (k, v) => `const double ${k} = ${v};`);
block('Sizes', t.size, (k, v) => `const double ${k} = ${v};`);
block('MotionMs', t.motion, (k, v) => (Number.isInteger(v) ? `const int ${k} = ${v};` : `const double ${k} = ${v};`));
lines.push('class TypeStep {', '  const TypeStep(this.size, this.weight, this.lineHeight, this.lineHeightBengali);',
  '  final double size;', '  final int weight;', '  final double lineHeight;', '  final double lineHeightBengali;', '}', '');
block('TypeScale', t.typography.scale, (k, v) =>
  `const ${k} = TypeStep(${v.size}, ${v.weight}, ${v.lineHeight}, ${v.lineHeightBengali});`);
block('FontFamilies', t.typography.families, (k, v) => `const ${k} = '${v}';`);
emit('app/lib/core/theme/tokens.g.dart', lines.join('\n'));

const css = [':root{'];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
for (const [k, v] of Object.entries({ ...t.color.shared })) css.push(`--${kebab(k)}:${v};`);
const themeVars = (mode) => Object.entries({ ...t.color[mode], ...t.color.accessible_text[mode] })
  .filter(([k]) => !k.startsWith('_')).map(([k, v]) => `--${kebab(k)}:${v};`).join('');
css.push(themeVars('light'));
for (const [k, v] of Object.entries(t.radius)) css.push(`--radius-${kebab(k)}:${v}px;`);
for (const [k, v] of Object.entries(t.space)) css.push(`--space-${kebab(k)}:${v}px;`);
for (const [k, v] of Object.entries(t.motion)) if (k.endsWith('Ms')) css.push(`--motion-${kebab(k.slice(0, -2))}:${v}ms;`);
css.push('color-scheme:light;}');
css.push(`@media (prefers-color-scheme:dark){:root:not([data-theme="light"]){${themeVars('dark')}color-scheme:dark;}}`);
css.push(`:root[data-theme="dark"]{${themeVars('dark')}color-scheme:dark;}`);
css.push('@media (prefers-reduced-motion:reduce){*{animation-duration:.01ms!important;transition-duration:120ms!important}}');
emit('shared/web/tokens.css', css.join('\n') + '\n');
done('tokens');
