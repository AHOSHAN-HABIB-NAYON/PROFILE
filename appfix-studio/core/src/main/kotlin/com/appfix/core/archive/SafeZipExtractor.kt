package com.appfix.core.archive

import com.appfix.core.util.CancelToken
import com.appfix.core.util.OperationCancelledException
import com.appfix.core.util.PathSafety
import com.appfix.core.util.ProgressListener
import com.appfix.core.util.formatBytes
import java.io.File
import java.util.zip.ZipFile

/** Archive rejected because it is unsafe to extract. The import is aborted and nothing is kept. */
class ArchiveSecurityException(message: String) : RuntimeException(message)

data class ExtractionPolicy(
    val maxEntries: Int = 50_000,
    val maxTotalBytes: Long = 2L * 1024 * 1024 * 1024,
    val maxEntryBytes: Long = 512L * 1024 * 1024,
    /** Ratio of uncompressed to compressed size above which a large entry is treated as a zip bomb. */
    val maxCompressionRatio: Long = 250,
    /** Windows/script executables are never extracted into a project workspace. */
    val blockedExtensions: Set<String> = setOf("exe", "dll", "scr", "com", "msi", "vbs", "ps1", "cmd", "bat", "pif", "cpl", "hta", "jse", "wsf"),
    /** Known OS metadata folders that are dropped silently. */
    val ignoredPrefixes: List<String> = listOf("__MACOSX/"),
    val ignoredNames: Set<String> = setOf(".DS_Store", "Thumbs.db", "desktop.ini"),
    /** Build outputs are dropped to save space; they are regenerated by a build. */
    val skipBuildOutputs: Boolean = true,
)

data class SkippedEntry(val name: String, val reason: String)

data class ExtractionResult(
    val filesWritten: Int,
    val bytesWritten: Long,
    val skipped: List<SkippedEntry>,
    val warnings: List<String>,
)

/**
 * Extracts a ZIP archive into a fresh, controlled directory.
 *
 * Security rules:
 * - Any entry whose path is absolute, contains `..`, a NUL byte or a drive letter aborts the import.
 * - Symbolic-link entries are never materialised.
 * - Declared and *actual* sizes are both enforced, so headers that lie about size cannot exhaust storage.
 * - Encrypted archives are rejected.
 * - Blocked executable types are skipped and reported.
 * - Nothing is ever marked executable.
 * On any failure or cancellation the destination directory is deleted.
 */
class SafeZipExtractor(private val policy: ExtractionPolicy = ExtractionPolicy()) {

    fun extract(
        archive: File,
        destination: File,
        cancel: CancelToken = CancelToken.NONE,
        progress: ProgressListener = ProgressListener.NONE,
    ): ExtractionResult {
        require(!destination.exists() || (destination.isDirectory && destination.list().isNullOrEmpty())) {
            "Destination must be a new, empty directory"
        }
        val cd = try {
            ZipCentralDirectory.read(archive)
        } catch (e: InvalidArchiveException) {
            throw InvalidArchiveException("Not a valid ZIP archive: ${e.message}")
        }
        if (cd.entries.size > policy.maxEntries) {
            throw ArchiveSecurityException("Archive has ${cd.entries.size} entries; the limit is ${policy.maxEntries}.")
        }
        val skipped = mutableListOf<SkippedEntry>()
        val warnings = mutableListOf<String>()
        val plan = mutableListOf<Pair<ZipCentralDirectory.Entry, String>>()
        val seenLower = HashMap<String, String>()
        var declaredTotal = 0L

        for (e in cd.entries) {
            if (e.isEncrypted) throw ArchiveSecurityException("Archive is encrypted or password-protected; it cannot be imported.")
            val rawName = e.name
            if (policy.ignoredPrefixes.any { rawName.startsWith(it) }) continue
            val norm = PathSafety.normalizeRelative(rawName)
                ?: if (rawName.trim('/', '.').isEmpty()) continue else throw ArchiveSecurityException(
                    "Unsafe path in archive: \"${rawName.take(200)}\". Archives with absolute paths or '..' segments are rejected.",
                )
            if (e.isSymlink) { skipped += SkippedEntry(norm, "symbolic link"); continue }
            if (e.isDirectory) continue
            val fileName = norm.substringAfterLast('/')
            if (fileName in policy.ignoredNames) continue
            if (policy.skipBuildOutputs && isBuildOutput(norm)) { skipped += SkippedEntry(norm, "build output"); continue }
            val ext = fileName.substringAfterLast('.', "").lowercase()
            if (ext in policy.blockedExtensions) { skipped += SkippedEntry(norm, "blocked executable type .$ext"); continue }
            if (e.uncompressedSize > policy.maxEntryBytes) {
                throw ArchiveSecurityException("$norm is ${formatBytes(e.uncompressedSize)}; the per-file limit is ${formatBytes(policy.maxEntryBytes)}.")
            }
            if (e.compressedSize > 0 && e.uncompressedSize > 10L * 1024 * 1024 && e.uncompressedSize / e.compressedSize > policy.maxCompressionRatio) {
                throw ArchiveSecurityException("$norm has a suspicious compression ratio (possible zip bomb).")
            }
            declaredTotal += e.uncompressedSize
            if (declaredTotal > policy.maxTotalBytes) {
                throw ArchiveSecurityException("Archive expands to more than ${formatBytes(policy.maxTotalBytes)}.")
            }
            val lower = norm.lowercase()
            val previous = seenLower.put(lower, norm)
            if (previous != null) {
                if (previous == norm) { warnings += "Duplicate entry $norm; the first copy was kept."; continue }
                warnings += "$norm and $previous differ only by letter case; Android storage may treat them as the same file."
            }
            if (fileName == "gradlew" || ext == "sh") warnings += "$norm is a shell script. It was extracted but is never executed on this device."
            plan += e to norm
        }

        destination.mkdirs()
        val destRoot = destination.canonicalFile
        var written = 0
        var bytes = 0L
        try {
            ZipFile(archive).use { zip ->
                val buf = ByteArray(64 * 1024)
                for ((entry, norm) in plan) {
                    cancel.throwIfCancelled()
                    val target = File(destRoot, norm)
                    if (!PathSafety.isInside(destRoot, target)) throw ArchiveSecurityException("Entry $norm resolves outside the project directory.")
                    val ze = zip.getEntry(entry.name) ?: throw InvalidArchiveException("Entry ${entry.name} is listed but unreadable")
                    target.parentFile?.mkdirs()
                    if (target.isDirectory) { skipped += SkippedEntry(norm, "conflicts with a directory"); continue }
                    var entryBytes = 0L
                    zip.getInputStream(ze).use { input ->
                        target.outputStream().buffered().use { out ->
                            while (true) {
                                cancel.throwIfCancelled()
                                val n = input.read(buf)
                                if (n < 0) break
                                entryBytes += n
                                bytes += n
                                if (entryBytes > policy.maxEntryBytes || (entry.uncompressedSize >= 0 && entryBytes > entry.uncompressedSize + 1024)) {
                                    throw ArchiveSecurityException("$norm is larger than its header declares; the archive was rejected.")
                                }
                                if (bytes > policy.maxTotalBytes) throw ArchiveSecurityException("Archive expands to more than ${formatBytes(policy.maxTotalBytes)}.")
                                out.write(buf, 0, n)
                            }
                        }
                    }
                    written++
                    progress.onProgress(bytes, declaredTotal, norm)
                }
            }
        } catch (t: Throwable) {
            destination.deleteRecursively()
            if (t is OperationCancelledException) throw t
            throw t
        }
        return ExtractionResult(written, bytes, skipped, warnings.distinct())
    }

    companion object {
        private val buildDirs = setOf("build", ".gradle", ".idea", ".cxx", ".externalNativeBuild", "node_modules", ".dart_tool", "Pods", ".kotlin")

        fun isBuildOutput(path: String): Boolean = path.split('/').dropLast(1).any { it in buildDirs }
    }
}
