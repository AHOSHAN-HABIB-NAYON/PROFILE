// Release signing is read from environment variables so no secrets live in the repo.
// See README.md -> "Signing a release build".
val releaseKeystorePath: String? = System.getenv("NAYON_KEYSTORE_PATH")?.takeIf { it.isNotBlank() }

// Every CI build gets a higher version, so a phone always installs it as an update and the
// build number is visible in the app (Settings > About). Local builds use 0.
val ciBuildNumber: Int = System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull() ?: 0

android {
    namespace = "com.webtecit.nayon"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.webtecit.nayon"
        minSdk = 24
        targetSdk = 36
        versionCode = 200 + ciBuildNumber
        versionName = "0.2.$ciBuildNumber"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
    }

    signingConfigs {
        // Debug-only key committed on purpose so every CI test build can install over the
        // previous one. It is NOT used for releases and must never sign a Play Store build.
        getByName("debug") {
            storeFile = file("debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        if (releaseKeystorePath != null) {
            create("release") {
                storeFile = file(releaseKeystorePath)
                storePassword = System.getenv("NAYON_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("NAYON_KEY_ALIAS")
                keyPassword = System.getenv("NAYON_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            if (releaseKeystorePath != null) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    testOptions {
        unitTests.isIncludeAndroidResources = true
    }

    lint {
        abortOnError = true
        checkDependencies = false
        // Version-upgrade hints should not break CI; they are reviewed manually.
        disable += setOf("GradleDependency", "AndroidGradlePluginVersion", "NewerVersionAvailable", "OldTargetApi")
    }
}

